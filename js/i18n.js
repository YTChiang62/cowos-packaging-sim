export function hasOwnCopy(lang, key) {
  const table = dict[lang];
  return !!(table && Object.prototype.hasOwnProperty.call(table, key) && table[key]);
}

export function t(lang, key, vars = {}) {
  const table = dict[lang] || dict["zh-TW"];
  let s = table[key] ?? dict["zh-TW"][key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function applyStaticI18n(lang, root = document) {
  root.documentElement?.setAttribute?.("lang", lang === "en" ? "en" : lang === "zh-CN" ? "zh-Hans" : "zh-Hant");
  const scope = root.querySelectorAll ? root : document;
  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(lang, el.dataset.i18n);
  });
}
