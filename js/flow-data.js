const p = (id, name, value, unit = "") => ({ id, name, value, unit });

function S(id, code, stage, tool, morphIn, morphOut, dock, name, params, extra = {}) {
  const lot = extra.carrier
    || (dock === "TRAY" || dock === "ATT" || dock === "FIN" ? "TRAY" : "FOUP");
  return {
    id,
    code,
    stage,
    tool,
    morphIn,
    morphOut,
    dock,
    present: extra.present || presentFor(dock),
    dur: extra.dur ?? 0.55,
    hold: extra.hold || null,
    name,
    params,
    split: !!extra.split,
    carrier: lot,
  };
}

function presentFor(dock) {
  if (dock === "SUB" || dock === "SUBIN") return "sub";
  if (dock === "KGD") return "kgd";
  if (dock === "ATT") return "att";
  if (dock === "FIN") return "fin";
  if (dock === "TRAY") return "tray";
  return "foup";
}

